const { chromium } = require('playwright-core');
(async()=>{
  const browser = await chromium.launch({headless:true, executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
  const page = await browser.newPage({ viewport:{width:1280,height:900}, reducedMotion:'reduce' });
  const errors=[];
  const requests=[];
  page.on('pageerror', e=>errors.push(e.message));
  page.on('request', req=>requests.push(req.url()));
  await page.goto('http://127.0.0.1:4318/index.html', {waitUntil:'networkidle'});
  const initial = await page.evaluate(()=>({entry:document.querySelector('#entry-screen')?.open, truth:document.querySelector('#entry-truth')?.textContent.trim(), url:location.hash}));
  await page.locator('#entry-truth').click();
  const spoilerOpen = await page.locator('#spoiler-dialog').evaluate(el=>el.open);
  const spoilerText = await page.locator('#spoiler-dialog').innerText();
  await page.locator('#spoiler-yes').click();
  await page.waitForTimeout(100);
  const truth = await page.evaluate(()=>({hash:location.hash, readerHidden:document.querySelector('#world-webtoon-reader')?.hidden, title:document.querySelector('#world-webtoon-reader .webtoon-reader-title')?.textContent.trim(), empty:document.querySelectorAll('.webtoon-page-empty').length}));
  await page.goto('http://127.0.0.1:4318/index.html', {waitUntil:'networkidle'});
  await page.locator('#entry-enter').click();
  await page.waitForTimeout(50);
  await page.locator('[data-nav-target="world"]').click();
  await page.waitForTimeout(50);
  const cards = await page.locator('[data-webtoon-book]').count();
  await page.locator('[data-webtoon-book="main-story"]').click();
  await page.waitForTimeout(100);
  const main = await page.evaluate(()=>({hash:location.hash, readerHidden:document.querySelector('#world-webtoon-reader')?.hidden, title:document.querySelector('#world-webtoon-reader .webtoon-reader-title')?.textContent.trim(), pages:document.querySelectorAll('#world-webtoon-reader .webtoon-page').length}));
  const badRequests = requests.filter(url=>url.includes('nma/index.html')||url.includes('entry-incident.js'));
  console.log(JSON.stringify({initial,spoilerOpen,spoilerText:spoilerText.slice(0,80),truth, cards,main,errors,badRequests},null,2));
  await browser.close();
})().catch(err=>{console.error(err);process.exitCode=1});
